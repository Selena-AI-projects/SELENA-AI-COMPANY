/**
 * Generates lib/data/blur-map.ts: a tiny blurred stand-in for every cinematic
 * frame, so a frame fades up from its own colours instead of appearing in a
 * hole. Next.js only derives these automatically for statically imported
 * images, and every frame here is addressed by path from the content files.
 *
 * Usage: node scripts/build-blur-map.mjs
 */

import { readdirSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const sharp = require("sharp");

const ROOT = path.resolve("public/media/cinematic");
const OUT = path.resolve("lib/data/blur-map.ts");

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = path.join(dir, entry);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = walk(ROOT)
  .filter((file) => /\.(webp|jpg|jpeg|png)$/i.test(file))
  .sort();

const entries = [];
for (const file of files) {
  // 12px wide is enough for the colour field and keeps each string ~200 bytes.
  const buffer = await sharp(file).resize(12, null, { fit: "inside" }).webp({ quality: 30 }).toBuffer();
  const key = `/${path.relative(path.resolve("public"), file).split(path.sep).join("/")}`;
  entries.push([key, `data:image/webp;base64,${buffer.toString("base64")}`]);
}

const body = entries.map(([key, value]) => `  "${key}":\n    "${value}",`).join("\n");

writeFileSync(
  OUT,
  `/**
 * Blurred stand-ins for the cinematic frames, keyed by public path.
 *
 * Generated by scripts/build-blur-map.mjs — do not edit by hand. Re-run it
 * after adding or replacing a frame.
 */
const BLUR_MAP: Record<string, string> = {
${body}
};

/** The frame's blurred stand-in, or undefined for an image without one. */
export function blurFor(src: string): string | undefined {
  return BLUR_MAP[src];
}
`,
  "utf8",
);

const bytes = entries.reduce((total, [, value]) => total + value.length, 0);
console.log(`${entries.length} кадров, ${Math.round(bytes / 1024)} KB в карте`);
